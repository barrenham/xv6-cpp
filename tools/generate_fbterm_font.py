#!/usr/bin/env python3
"""Generate the checked-in XV Mono grayscale atlas (optional Pillow/FreeType tool)."""
import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--font', type=Path, required=True)
parser.add_argument('--output', type=Path, required=True)
args = parser.parse_args()
font = ImageFont.truetype(str(args.font), 16)
width, height, baseline = 10, 20, 16
assert font.getlength('M') <= width
lines = ['#pragma once', '', 'namespace fbterm', '{',
         '// XV Mono: grayscale raster derived from DejaVu Sans Mono; see FONT-LICENSE.txt.',
         '// Generated by tools/generate_fbterm_font.py; 4-bit coverage, never stretched.',
         '// Source TTF SHA-256: ' + hashlib.sha256(args.font.read_bytes()).hexdigest(),
         'inline constexpr unsigned font_width = 10;',
         'inline constexpr unsigned font_height = 20;',
         'inline constexpr unsigned char font[95][font_width * font_height] = {']
for code in range(32, 127):
    image = Image.new('L', (width, height), 0)
    ImageDraw.Draw(image).text((0, baseline), chr(code), font=font, fill=255, anchor='ls')
    values = [(pixel * 15 + 127) // 255 for pixel in image.getdata()]
    lines.append(f'  {{ // U+{code:04X}')
    for row in range(height):
        lines.append('    ' + ','.join(str(v) for v in values[row*width:(row+1)*width]) + ',')
    lines.append('  },')
lines += ['};', '} // namespace fbterm', '']
args.output.write_text('\n'.join(lines))
